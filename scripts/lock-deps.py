"""Write tested runtime/dev dependency versions without leaking editable paths."""
import importlib.metadata
import tomllib
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

root = Path(__file__).resolve().parent.parent
project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]


def resolve(requirements):
    resolved = {}
    visited = set()

    def visit(raw):
        requirement = Requirement(raw)
        name = canonicalize_name(requirement.name)
        key = (name, tuple(sorted(requirement.extras)))
        if key in visited:
            return
        visited.add(key)
        distribution = importlib.metadata.distribution(name)
        resolved[name] = distribution.version
        for dependency in distribution.requires or []:
            candidate = Requirement(dependency)
            applicable = candidate.marker is None
            for extra in {"", *requirement.extras}:
                for platform in ["win32", "linux", "darwin"]:
                    environment = {**default_environment(), "extra": extra, "sys_platform": platform}
                    if candidate.marker and candidate.marker.evaluate(environment):
                        applicable = True
            if applicable:
                visit(dependency)

    for requirement in requirements:
        visit(requirement)
    return "# Tested on Python 3.12; generated by scripts/lock-deps.py.\n" + "".join(
        name + "==" + version + "\n" for name, version in sorted(resolved.items())
    )


(root / "requirements.lock").write_text(resolve(project["dependencies"]), encoding="utf-8")
(root / "requirements-dev.lock").write_text(
    resolve(project["dependencies"] + project["optional-dependencies"]["dev"]), encoding="utf-8"
)
print("Runtime and development locks written.")
