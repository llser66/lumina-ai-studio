import { expect, Page, test } from '@playwright/test';

async function signUp(page: Page) {
  await page.goto('/studio');
  await page.getByRole('button', { name: '登录账号', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: '创建账号', exact: true }).click();
  await dialog.getByLabel('你的名字').fill('模型配置测试');
  await dialog.getByLabel('邮箱', { exact: true }).fill('models-' + crypto.randomUUID() + '@example.com');
  await dialog.getByLabel('密码', { exact: true }).fill('test-only-models-password');
  await dialog.getByRole('button', { name: '创建账号', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: '模型与订阅', exact: true }).click();
  await expect(page.locator('.provider-card')).toHaveCount(10);
}

test('model configuration saves keys privately and drives the selected image model', async ({ page }) => {
  await signUp(page);
  if (await page.getByRole('button', { name: '关闭提示' }).isVisible()) await page.getByRole('button', { name: '关闭提示' }).click();
  await page.screenshot({ path: 'docs/screenshot-models.png', fullPage: true });
  await page.locator('.provider-openrouter').getByRole('button', { name: '添加连接' }).click();
  const dialog = page.getByRole('dialog', { name: '连接模型账号' });
  await dialog.getByLabel('连接名称').fill('测试 OpenRouter');
  await dialog.getByRole('textbox', { name: 'API Key' }).fill('test-only-openrouter-secret-1234');
  await dialog.getByRole('button', { name: '保存连接' }).click();
  await expect(dialog).not.toBeVisible();
  const connection = page.locator('.connection-row').filter({ hasText: '测试 OpenRouter' });
  await expect(connection).toBeVisible();
  await connection.getByRole('button', { name: '验证凭证' }).click();
  await expect(connection).toContainText('上次验证通过');
  const config = await page.evaluate(async () => (await fetch('/api/models/config')).json());
  expect(JSON.stringify(config)).not.toContain('test-only-openrouter-secret');
  const row = config.connections[0];
  await page.getByLabel('模型连接', { exact: true }).first().selectOption(row.id);
  const model = row.image_models[0].id;
  await page.getByLabel('生图模型', { exact: true }).selectOption(model);
  await page.getByRole('button', { name: '保存默认模型' }).click();
  await expect(page.getByRole('status')).toContainText('默认模型已保存');
  await page.reload();
  await expect(page.getByLabel('生图模型', { exact: true })).toHaveValue(model);
  await page.getByRole('button', { name: '创作工作台', exact: true }).click();
  const prompt = 'A blue bottle in an editorial studio';
  await page.getByRole('textbox', { name: '画面描述' }).fill(prompt);
  await page.getByRole('button', { name: /开始生成/ }).click();
  await expect(page.locator('.art-card').filter({ hasText: prompt })).toContainText('已完成', { timeout: 15000 });
  const jobs = await page.evaluate(async () => (await fetch('/api/jobs')).json());
  expect(jobs.items[0].model).toBe(model);
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
  expect(storage).not.toContain('test-only-openrouter-secret');
  await page.getByRole('button', { name: '模型与订阅', exact: true }).click();
  await page.getByRole('button', { name: '断开连接：测试 OpenRouter' }).click();
  await page.getByRole('dialog', { name: '断开模型连接' }).getByRole('button', { name: '确认断开' }).click();
  await expect(page.locator('.connection-row')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '生图服务待连接' })).toBeVisible();
});

test('subscription authorization completes through web prompts without exposing tokens', async ({ page }) => {
  await signUp(page);
  await page.locator('.provider-github-copilot').getByRole('button', { name: '添加连接' }).click();
  const dialog = page.getByRole('dialog', { name: '连接模型账号' });
  await dialog.getByLabel('连接名称').fill('测试 Copilot 订阅');
  await dialog.getByRole('button', { name: '开始账号授权' }).click();
  await expect(dialog).toContainText('TEST-1234');
  await dialog.getByLabel('GitHub domain', { exact: true }).fill('github.com');
  await dialog.getByRole('button', { name: '提交授权信息' }).click();
  await expect(dialog).toContainText('账号已连接', { timeout: 10000 });
  await dialog.getByRole('button', { name: '完成，选择默认模型' }).click();
  await expect(page.locator('.connection-row').filter({ hasText: '测试 Copilot 订阅' })).toContainText('订阅');
  const config = await page.evaluate(async () => (await fetch('/api/models/config')).json());
  expect(JSON.stringify(config)).not.toContain('test-only-access-token');
  const row = config.connections[0];
  await page.getByLabel('模型连接', { exact: true }).nth(1).selectOption(row.id);
  await page.getByLabel('文本模型', { exact: true }).selectOption(row.chat_models[0].id);
  await page.getByRole('button', { name: '保存默认模型' }).click();
  await expect(page.getByRole('status')).toContainText('默认模型已保存');
});

test('Cloudflare free-tier image connection saves the account ID and token privately', async ({ page }) => {
  await signUp(page);
  await page.locator('.provider-cloudflare').getByRole('button', { name: '添加连接' }).click();
  const dialog = page.getByRole('dialog', { name: '连接模型账号' });
  await expect(dialog).toContainText('FLUX.1 schnell');
  await dialog.getByLabel('连接名称').fill('测试 Cloudflare');
  await dialog.getByRole('textbox', { name: 'API Key' }).fill('test-only-cloudflare-token');
  await dialog.getByLabel('Cloudflare Account ID').fill('0123456789abcdef0123456789abcdef');
  await dialog.getByRole('button', { name: '保存连接' }).click();
  await expect(dialog).not.toBeVisible();
  const config = await page.evaluate(async () => (await fetch('/api/models/config')).json());
  expect(JSON.stringify(config)).not.toContain('test-only-cloudflare-token');
  expect(JSON.stringify(config)).not.toContain('0123456789abcdef0123456789abcdef');
  const row = config.connections.find((item: { provider: string }) => item.provider === 'cloudflare');
  expect(row.image_models.map((model: { id: string }) => model.id)).toEqual(['@cf/black-forest-labs/flux-1-schnell']);
  await page.locator('.provider-deepseek').getByRole('button', { name: '添加连接' }).click();
  const textDialog = page.getByRole('dialog', { name: '连接模型账号' });
  await textDialog.getByLabel('连接名称').fill('测试文本模型');
  await textDialog.getByRole('textbox', { name: 'API Key' }).fill('test-only-deepseek-token');
  await textDialog.getByRole('button', { name: '保存连接' }).click();
  await expect(textDialog).not.toBeVisible();
  const textConfig = await page.evaluate(async () => (await fetch('/api/models/config')).json());
  const textRow = textConfig.connections.find((item: { provider: string }) => item.provider === 'deepseek');
  await page.getByLabel('模型连接', { exact: true }).first().selectOption(row.id);
  await page.getByLabel('模型连接', { exact: true }).nth(1).selectOption(textRow.id);
  await page.getByRole('button', { name: '保存默认模型' }).click();
  await expect(page.getByLabel('生图模型', { exact: true })).toHaveValue('@cf/black-forest-labs/flux-1-schnell');
});

